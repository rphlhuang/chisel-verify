"""Miter construction: wrapper SV + yosys script -> btor2.

The wrapper instantiates the (yosys-renamed) golden and gate designs, aligns
latencies with input delay registers, applies waiver assumes on the raw inputs,
and asserts the (possibly waiver-relaxed) output comparison once pipelines fill.
"""

import subprocess
from pathlib import Path

from .fmt import FpFormat
from .jobs import Job, Design
from .tools import tool
from .waivers import Waiver, input_assume_exprs, output_compare_expr

LAYER_MARKER = "----- 8< -----"


def strip_firtool_layers(src: Path, dst: Path) -> None:
    """firtool single-file output appends `include`-based verification layer stubs
    after an 8< marker; yosys chokes on the includes. Keep only the core design."""
    text = src.read_text()
    idx = text.find(LAYER_MARKER)
    dst.write_text(text[:idx] if idx != -1 else text)


def _instance(d: Design, inst_module: str, inst_name: str, fmt: FpFormat,
              a: str, b: str, out: str, rst: str) -> list[str]:
    conns = [
        f".{d.port('a')}({a})",
        f".{d.port('b')}({b})",
        f".{d.port('out')}({out})",
    ]
    if d.port("clock"):
        conns.append(f".{d.port('clock')}(clock)")
    if d.port("reset"):
        conns.append(f".{d.port('reset')}({rst})")
    for role in ("valid_in", "en"):
        if d.port(role):
            conns.append(f".{d.port(role)}(1'b1)")
    if d.port("valid_out"):
        conns.append(f".{d.port('valid_out')}({inst_name}_valid)")
    for port, val in d.tie.items():
        conns.append(f".{port}({val})")
    lines = []
    if d.port("valid_out"):
        lines.append(f"  wire {inst_name}_valid;")
    lines.append(f"  {inst_module} {inst_name}({', '.join(conns)});")
    return lines


def _delay_line(prefix: str, sig: str, width: int, depth: int) -> tuple[list[str], str]:
    """Registers delaying `sig` by `depth` cycles; returns (lines, final_name)."""
    if depth == 0:
        return [], sig
    lines = []
    cur = sig
    for i in range(1, depth + 1):
        nxt = f"{prefix}_d{i}"
        lines.append(f"  reg [{width-1}:0] {nxt};")
        lines.append(f"  always @(posedge clock) {nxt} <= {cur};")
        cur = nxt
    return lines, cur


def generate_miter_sv(job: Job, waivers: list[Waiver], blocks: list[Waiver]) -> str:
    f = job.fmt
    w = f.width
    lmax = job.max_latency
    cmp_start = 0 if lmax == 0 else lmax + 1

    L = []
    L.append("// generated by fpdiff -- do not edit")
    L.append(f"module fpdiff_miter(input clock, input [{w-1}:0] a, input [{w-1}:0] b);")
    L.append("")
    L.append("  reg [15:0] fpdiff_cycles = 16'd0;")
    L.append("  always @(posedge clock) fpdiff_cycles <= fpdiff_cycles + 16'd1;")
    L.append("  wire fpdiff_rst = (fpdiff_cycles == 16'd0);")
    L.append("")

    # latency alignment: each side sees inputs delayed by (lmax - own latency)
    for side, d in (("gold", job.gold), ("gate", job.gate)):
        depth = lmax - d.latency
        la, a_sig = _delay_line(f"a_{side}", "a", w, depth)
        lb, b_sig = _delay_line(f"b_{side}", "b", w, depth)
        L += la + lb
        L.append(f"  wire [{w-1}:0] out_{side};")
        L += _instance(d, f"fpdiff_{side}", f"{side}_i", f,
                       a_sig, b_sig, f"out_{side}", "fpdiff_rst")
        L.append("")

    for wid, expr in input_assume_exprs(list(waivers) + list(blocks), f):
        L.append(f"  // assume: {wid}")
        L.append(f"  always @* assume({expr});")
    L.append("")

    cmp_expr = output_compare_expr(waivers, f)
    L.append(f"  wire fpdiff_cmp_en = (fpdiff_cycles >= 16'd{cmp_start});")
    L.append(f"  wire fpdiff_outputs_ok = {cmp_expr};")
    L.append("  always @* if (fpdiff_cmp_en) assert(fpdiff_outputs_ok);")
    for side, d in (("gold", job.gold), ("gate", job.gate)):
        if d.port("valid_out"):
            L.append(f"  always @* if (fpdiff_cmp_en) assert({side}_i_valid);")
    L.append("endmodule")
    return "\n".join(L) + "\n"


def generate_cover_sv(job: Job, waivers: list[Waiver], pred: str) -> str:
    """Standalone module: bad state reachable iff `pred` satisfiable under assumes."""
    f = job.fmt
    w = f.width
    L = [f"module fpdiff_cover(input clock, input [{w-1}:0] a, input [{w-1}:0] b);"]
    for wid, expr in input_assume_exprs(waivers, f):
        L.append(f"  always @* assume({expr});  // {wid}")
    L.append(f"  always @* assert(!({pred}));")
    L.append("endmodule")
    return "\n".join(L) + "\n"


def yosys_miter_script(job: Job, work: Path, srcs: dict[str, list[Path]]) -> str:
    lines = []
    for side in ("gold", "gate"):
        d = getattr(job, side)
        for p in srcs[side]:
            lines.append(f"read_verilog -sv -formal {p}")
        lines.append(f"prep -top {d.top}")
        lines.append("flatten")
        if d.top != f"fpdiff_{side}":
            lines.append(f"rename {d.top} fpdiff_{side}")
        lines.append(f"design -stash {side}")
    lines.append(f"read_verilog -sv -formal {work / 'miter.sv'}")
    lines.append("design -copy-from gold -as fpdiff_gold fpdiff_gold")
    lines.append("design -copy-from gate -as fpdiff_gate fpdiff_gate")
    lines.append("prep -top fpdiff_miter")
    lines.append("flatten")
    # yosys >= 0.36 parses SV assert/assume into unified $check cells, which
    # write_btor silently ignores; lower them back to $assert/$assume first.
    lines.append("chformal -lower")
    lines.append(f"write_btor -x {work / 'miter.btor'}")
    return "\n".join(lines) + "\n"


def build_miter(job: Job, waivers: list[Waiver], blocks: list[Waiver]) -> Path:
    """Preprocess sources, emit wrapper, run yosys; returns path to miter.btor."""
    work = job.out_dir
    work.mkdir(parents=True, exist_ok=True)

    srcs: dict[str, list[Path]] = {}
    for side in ("gold", "gate"):
        d = getattr(job, side)
        outs = []
        for i, fpath in enumerate(d.files):
            src = job.resolve(fpath)
            dst = work / f"{side}_{i}_{src.name}"
            strip_firtool_layers(src, dst)
            outs.append(dst)
        srcs[side] = outs

    (work / "miter.sv").write_text(generate_miter_sv(job, waivers, blocks))
    script = work / "miter.ys"
    script.write_text(yosys_miter_script(job, work, srcs))

    r = subprocess.run([tool("yosys"), "-q", str(script)],
                       capture_output=True, text=True)
    if r.returncode != 0:
        raise RuntimeError(f"yosys failed:\n{r.stdout}\n{r.stderr}")
    return work / "miter.btor"


def build_cover(job: Job, waivers: list[Waiver], pred: str, tag: str) -> Path:
    work = job.out_dir
    work.mkdir(parents=True, exist_ok=True)
    sv = work / f"cover_{tag}.sv"
    sv.write_text(generate_cover_sv(job, waivers, pred))
    script = work / f"cover_{tag}.ys"
    btor = work / f"cover_{tag}.btor"
    script.write_text(
        f"read_verilog -sv -formal {sv}\nprep -top fpdiff_cover\n"
        f"chformal -lower\nwrite_btor -x {btor}\n")
    r = subprocess.run([tool("yosys"), "-q", str(script)],
                       capture_output=True, text=True)
    if r.returncode != 0:
        raise RuntimeError(f"yosys failed:\n{r.stdout}\n{r.stderr}")
    return btor
