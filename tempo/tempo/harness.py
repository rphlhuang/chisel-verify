"""Harness: DUT + compiled monitor -> btor2 via yosys.

The solver drives every DUT input freely each cycle (a maximally hostile
environment) *except* as constrained by `assume` properties — which is the whole
point: environment assumptions are the knob the human turns during triage.
"""

import re
import subprocess
from pathlib import Path

from .ast import Project
from .compiler import compile_monitor
from .tools import tool


def parse_ports(sv: str, top: str) -> dict[str, tuple[str, int]]:
    """Parse firtool-style module header -> {port: (dir, width)}."""
    m = re.search(rf"module\s+{re.escape(top)}\s*\((.*?)\);", sv, re.S)
    if not m:
        raise ValueError(f"module {top} not found")
    ports, direction, width = {}, None, 1
    for tok in m.group(1).split(","):
        tok = tok.strip()
        dm = re.match(r"(input|output|inout)\s*(\[(\d+):(\d+)\])?\s*(\w+)", tok)
        if dm:
            direction = dm.group(1)
            width = (int(dm.group(3)) - int(dm.group(4)) + 1) if dm.group(2) else 1
            name = dm.group(5)
        else:
            wm = re.match(r"(\[(\d+):(\d+)\])?\s*(\w+)", tok)
            if not wm:
                continue
            if wm.group(1):
                width = int(wm.group(2)) - int(wm.group(3)) + 1
            name = wm.group(4)
        ports[name] = (direction, width)
    return ports


def generate_top(proj: Project, ports: dict[str, tuple[str, int]]) -> str:
    ins = [(n, w) for n, (d, w) in ports.items()
           if d == "input" and n not in (proj.clock, proj.reset)]
    outs = [(n, w) for n, (d, w) in ports.items() if d == "output"]

    L = ["// generated by tempo -- do not edit"]
    hdr = ["input clock"] + [f"input {f'[{w-1}:0] ' if w>1 else ''}{n}" for n, w in ins]
    L.append("module tempo_top(\n  " + ",\n  ".join(hdr) + "\n);")
    L.append("  reg [15:0] t = 16'd0;")
    L.append("  always @(posedge clock) t <= t + 16'd1;")
    L.append("  wire rst = (t == 16'd0);")
    for n, w in outs:
        L.append(f"  wire {f'[{w-1}:0] ' if w>1 else ''}{n};")
    conns = [f".{proj.clock}(clock)"]
    if proj.reset:
        conns.append(f".{proj.reset}(rst)")
    conns += [f".{n}({n})" for n, _ in ins + outs]
    L.append(f"  {proj.dut_top} dut({', '.join(conns)});")
    mconns = [".clock(clock)", ".dis(rst)"] + [f".{s}({s})" for s in proj.signals]
    L.append(f"  tempo_monitor mon({', '.join(mconns)});")
    L.append("endmodule")
    return "\n".join(L) + "\n"


def build(proj: Project, out_dir: Path) -> Path:
    out_dir.mkdir(parents=True, exist_ok=True)
    dut_srcs = [Path(f).resolve() for f in proj.dut_files]
    ports = parse_ports(dut_srcs[0].read_text(), proj.dut_top)
    for s in proj.signals:
        if s not in ports:
            raise ValueError(f"monitored signal {s!r} is not a port of {proj.dut_top}")

    (out_dir / "monitor.v").write_text(compile_monitor(proj))
    (out_dir / "top.v").write_text(generate_top(proj, ports))
    btor = out_dir / "design.btor"
    script = [f"read_verilog -sv -formal -DTEMPO_FORMAL {p}"
              for p in [*dut_srcs, out_dir / "monitor.v", out_dir / "top.v"]]
    script += ["prep -top tempo_top", "flatten",
               "chformal -lower",       # yosys $check cells -> $assert/$assume (see fpdiff)
               f"write_btor -x {btor}"]
    (out_dir / "build.ys").write_text("\n".join(script) + "\n")
    r = subprocess.run([tool("yosys"), "-q", str(out_dir / "build.ys")],
                       capture_output=True, text=True)
    if r.returncode != 0:
        raise RuntimeError(f"yosys failed:\n{r.stdout}\n{r.stderr}")
    return btor
